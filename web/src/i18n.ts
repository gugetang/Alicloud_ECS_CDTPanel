// 中英切换（默认英文）：界面文案以中文原文作 key，英文翻译放在 EN 表里；
// 中文模式直接返回 key 本身。语言存在 localStorage `cdt-lang`。
import { useEffect, useState } from "react";

export type Lang = "en" | "zh";

let currentLang: Lang = (() => {
  try {
    const v = localStorage.getItem("cdt-lang");
    return v === "zh" || v === "en" ? (v as Lang) : "en";
  } catch {
    return "en";
  }
})();

const listeners = new Set<(l: Lang) => void>();

export function getLang(): Lang {
  return currentLang;
}

export function setLang(l: Lang) {
  currentLang = l;
  try {
    localStorage.setItem("cdt-lang", l);
  } catch {
    /* 忽略 */
  }
  listeners.forEach((f) => f(l));
}

export function useI18n() {
  const [lang, setLangState] = useState<Lang>(currentLang);
  useEffect(() => {
    const f = (l: Lang) => setLangState(l);
    listeners.add(f);
    return () => {
      listeners.delete(f);
    };
  }, []);
  return {
    lang,
    setLang,
    t: (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
  };
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = lang === "en" ? (EN[key] ?? key) : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

